    /**
     * Crea una base de datos nueva y, si se pide, le aplica el esquema heredado
     * con datos. Todas se eliminan con el contenedor.
     */
    private static String createDatabase(boolean legacy) throws SQLException {
        String name = "adopt_" + UUID.randomUUID().toString().replace("-", "");
        try (Connection admin = DriverManager.getConnection(
                PostgresIntegrationTestSupport.postgres().getJdbcUrl(),
                PostgresIntegrationTestSupport.postgres().getUsername(),
                PostgresIntegrationTestSupport.postgres().getPassword());
                Statement statement = admin.createStatement()) {
            statement.execute("CREATE DATABASE " + name);
        }
        if (legacy) {
            try (Connection connection = DriverManager.getConnection(url(name),
                    PostgresIntegrationTestSupport.postgres().getUsername(),
                    PostgresIntegrationTestSupport.postgres().getPassword());
                    Statement statement = connection.createStatement()) {
                // Se ejecutan sentencia a sentencia (el driver admite varias separadas por ';')
                statement.execute(LEGACY_SCHEMA);
                statement.execute(LEGACY_DATA);
            }
        }
        return name;
    }

    private static String url(String database) {
        var postgres = PostgresIntegrationTestSupport.postgres();
        return "jdbc:postgresql://" + postgres.getHost() + ":" + postgres.getMappedPort(5432) + "/" + database
                + "?loggerLevel=OFF";
    }

    private static JdbcTemplate jdbc(String database) {
        var postgres = PostgresIntegrationTestSupport.postgres();
        return new JdbcTemplate(new DriverManagerDataSource(url(database), postgres.getUsername(), postgres.getPassword()));
    }

    /**
     * Flyway configurado como la aplicación: mismas migraciones y los valores
     * {@code spring.flyway.baseline-*} leídos de {@code application.properties}.
     */
    private static Flyway flyway(String database) throws IOException {
        Properties properties = PropertiesLoaderUtils.loadProperties(new ClassPathResource("application.properties"));
        assertEquals("true", properties.getProperty("spring.flyway.baseline-on-migrate"));
        var postgres = PostgresIntegrationTestSupport.postgres();
        return Flyway.configure()
                .dataSource(url(database), postgres.getUsername(), postgres.getPassword())
                .locations("classpath:db/migration")
                .baselineOnMigrate(Boolean.parseBoolean(properties.getProperty("spring.flyway.baseline-on-migrate")))
                .baselineVersion(properties.getProperty("spring.flyway.baseline-version"))
                .load();
    }

    private static int count(JdbcTemplate jdbc, String table) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM " + table, Integer.class);
    }

    private static Instant epoch(JdbcTemplate jdbc, String sql) {
        return Instant.ofEpochMilli(Math.round(jdbc.queryForObject(sql, Double.class) * 1000));
    }
