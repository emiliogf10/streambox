    // Flyway sobre la base heredada
    // ------------------------------------------------------------------

    /**
     * La historia queda registrada: baseline en la versión 0 (por eso V1 SÍ se
     * ejecuta), luego V1, V2, V3 y V4, todas correctas. Una segunda ejecución no
     * hace nada y {@code validate} pasa (los checksums coinciden).
     */
    @Test
    void laAdopcionRegistraBaselineYTodasLasMigracionesYEsRepetible() throws Exception {
        String db = createDatabase(true);

        MigrateResult first = flyway(db).migrate();

        assertEquals(4, first.migrationsExecuted, "deben ejecutarse V1, V2, V3 y V4");
        List<Map<String, Object>> history = jdbc(db).queryForList(
                "SELECT version, description, type, success FROM flyway_schema_history ORDER BY installed_rank");
        assertEquals(List.of("0", "1", "2", "3", "4"), history.stream().map(r -> (String) r.get("version")).toList(), "" + history);
        assertEquals("BASELINE", history.get(0).get("type"));
        assertTrue(history.stream().allMatch(r -> Boolean.TRUE.equals(r.get("success"))));

        assertEquals(0, flyway(db).migrate().migrationsExecuted, "la segunda ejecución no debe hacer nada");
        flyway(db).validate();
    }

    /**
     * V1 es idempotente ({@code IF NOT EXISTS}) y no destruye datos: tras
     * adoptar, todas las filas y relaciones siguen ahí con los mismos valores
     * (incluido el texto con {@code ñ}).
     */
    @Test
    void laAdopcionConservaTodosLosDatos() throws Exception {
        String db = createDatabase(true);

        flyway(db).migrate();

        JdbcTemplate jdbc = jdbc(db);
        assertEquals(2, count(jdbc, "users"));
        assertEquals(2, count(jdbc, "movies"));
        assertEquals(2, count(jdbc, "genres"));
        assertEquals(1, count(jdbc, "movie_genres"));
        assertEquals(2, count(jdbc, "user_favorite_movies"), "alice tiene las dos películas");
        assertEquals(List.of("Alien", "Mañana"),
                jdbc.queryForList("SELECT title FROM movies ORDER BY title", String.class));
        assertEquals("hash-a", jdbc.queryForObject("SELECT password FROM users WHERE username = 'alice'", String.class));
        assertEquals(List.of("Acción", "Drama"),
                jdbc.queryForList("SELECT name FROM genres ORDER BY name", String.class));
    }

    /**
     * V1 completa lo que falta en la base heredada: los tres índices del
     * catálogo de películas (ver {@code idx_*}); {@code CREATE INDEX IF NOT
     * EXISTS} es lo único que V1 llega a añadir sobre tablas que ya existían.
     * Los otros son los de las tablas de series que crea V3 y los de
     * {@code refresh_tokens} que crea V4.
     */
    @Test
    void laAdopcionAnadeLosIndicesQueFaltaban() throws Exception {
        String db = createDatabase(true);
        JdbcTemplate jdbc = jdbc(db);
        assertEquals(List.of(), jdbc.queryForList(
                "SELECT indexname FROM pg_indexes WHERE schemaname = 'public' AND indexname LIKE 'idx\\_%'", String.class));

        flyway(db).migrate();

        // Se compara como conjunto: el orden de ORDER BY depende de la collation del servidor
        assertEquals(Set.of("idx_favorites_movie_id", "idx_movie_genres_genre_id", "idx_movies_release_year",
                        "idx_series_genres_genre_id", "idx_favorite_series_series_id", "idx_series_release_year",
                        "idx_refresh_tokens_user_id", "idx_refresh_tokens_family_id", "idx_refresh_tokens_replaced_by_id"),
                Set.copyOf(jdbc.queryForList("SELECT indexname FROM pg_indexes WHERE schemaname = 'public'"
                        + " AND indexname LIKE 'idx\\_%'", String.class)));
    }

    /**
     * V2 convierte {@code created_at} a {@code timestamptz} conservando los
     * datos, pero PostgreSQL interpreta el valor antiguo (sin zona) <b>en la zona
     * horaria de la sesión que ejecuta la migración</b>. El driver JDBC envía la
     * zona de la JVM, así que el instante resultante depende de la máquina que
     * ejecute Flyway. Este test lo fuerza explícitamente con tres zonas y
     * documenta el resultado observado: {@code 22:00} de junio queda como
     * {@code 20:00Z} en Madrid (UTC+2), {@code 22:00Z} en UTC y {@code 02:00Z} del
     * día siguiente en Nueva York (UTC-4). Es el aviso que figura en la cabecera
     * de V2: si la base heredada se escribió con otra zona que la del servidor que
     * migra, las fechas quedan desplazadas (solo afecta a {@code created_at}).
     */
    @ParameterizedTest(name = "zona de la sesión {0}")
    @CsvSource({
            "Europe/Madrid,    2020-06-15T20:00:00Z",
            "UTC,              2020-06-15T22:00:00Z",
            "America/New_York, 2020-06-16T02:00:00Z" })
    void v2InterpretaLasFechasAntiguasEnLaZonaHorariaDeLaSesion(String zone, String expectedInstant) throws Exception {
        String db = createDatabase(true);

        TimeZone previous = TimeZone.getDefault();
        try {
            TimeZone.setDefault(TimeZone.getTimeZone(zone));
            flyway(db).migrate(); // la conexión nueva de Flyway hereda la zona de la JVM
        } finally {
            TimeZone.setDefault(previous);
        }

        JdbcTemplate jdbc = jdbc(db);
        assertEquals("timestamp with time zone", jdbc.queryForObject(
                "SELECT data_type FROM information_schema.columns WHERE table_name = 'users' AND column_name = 'created_at'",
                String.class));
        Instant migrated = epoch(jdbc, "SELECT EXTRACT(EPOCH FROM created_at) FROM users WHERE username = 'alice'");
        assertEquals(Instant.parse(expectedInstant), migrated);
        // Y es exactamente "la hora antigua leída en esa zona": la regla se cumple para todas las filas
        Instant movieMigrated = epoch(jdbc, "SELECT EXTRACT(EPOCH FROM created_at) FROM movies WHERE title = 'Alien'");
        assertEquals(LocalDateTime.parse("2020-06-16T09:15:30").atZone(ZoneId.of(zone)).toInstant(), movieMigrated);
    }

    /**
     * Límite conocido de la adopción (se documenta, no se defiende): como V1 usa
     * {@code CREATE TABLE IF NOT EXISTS}, una base heredada conserva su esquema
     * original. Por tanto NO recibe (a) el {@code ON DELETE CASCADE} de las
     * tablas de unión ni (b) los CHECK de año y duración. Es exactamente lo que
     * dice la documentación de {@code MovieRepository.deleteFromAllFavorites}:
     * sin esa limpieza explícita, borrar una película con favoritos fallaría con
     * una violación de clave foránea. Si algún día se añade una migración que
     * unifique ambos esquemas, este test debe actualizarse.
     */
    @Test
    void laBaseAdoptadaNoRecibeLasCascadasNiLosCheckDeUnaBaseNueva() throws Exception {
        String db = createDatabase(true);
        flyway(db).migrate();
        JdbcTemplate jdbc = jdbc(db);

        // Solo las cuatro claves foráneas heredadas (las de V3 son nuevas y sí cascadan)
        assertEquals(List.of("NO ACTION", "NO ACTION", "NO ACTION", "NO ACTION"), jdbc.queryForList(
                "SELECT delete_rule FROM information_schema.referential_constraints"
                        + " WHERE constraint_schema = 'public' AND constraint_name LIKE 'fklegacy%'"
                        + " ORDER BY constraint_name", String.class));

        // Borrar una película con favoritos falla en la base heredada (en una nueva se encadena)
        DataIntegrityViolationException error = assertThrows(DataIntegrityViolationException.class,
                () -> jdbc.update("DELETE FROM movies WHERE title = 'Mañana'"));
        assertEquals("23503", PostgresIntegrationTestSupport.sqlState(error));

        // Y acepta un año imposible porque no tiene el CHECK de V1
        jdbc.update("INSERT INTO movies (title, description, duration, release_year, image_url, video_url, created_at)"
                + " VALUES ('Antigua', 'd', 100, 1700, 'u', 'v', now())");
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM movies WHERE release_year = 1700", Integer.class));
    }

    /**
     * A diferencia de las tablas de películas, las de series (V3) son nuevas
     * también en una base adoptada: se crean completas, con sus cascadas y sus
     * CHECK. Por eso, para series, no hace falta el equivalente de
     * {@code MovieRepository.deleteFromAllFavorites}: borrar una serie arrastra
     * episodios, géneros de la serie y favoritos aunque la base sea heredada, y
     * un género que use una serie sigue sin poder borrarse.
     */
    @Test
    void laBaseAdoptadaRecibeLasTablasDeSeriesCompletasConSusCascadas() throws Exception {
        String db = createDatabase(true);
        flyway(db).migrate();
        JdbcTemplate jdbc = jdbc(db);

        Map<String, String> rules = new java.util.HashMap<>();
        jdbc.queryForList("SELECT constraint_name, delete_rule FROM information_schema.referential_constraints"
                        + " WHERE constraint_schema = 'public'")
                .forEach(r -> rules.put((String) r.get("constraint_name"), (String) r.get("delete_rule")));
        assertEquals("CASCADE", rules.get("fk_series_genres_series"));
        assertEquals("NO ACTION", rules.get("fk_series_genres_genre"));
        assertEquals("CASCADE", rules.get("fk_episodes_series"));
        assertEquals("CASCADE", rules.get("fk_favorite_series_user"));
        assertEquals("CASCADE", rules.get("fk_favorite_series_series"));

        long seriesId = jdbc.queryForObject("INSERT INTO series (title, description, release_year, image_url, created_at)"
                + " VALUES ('Heredada', 'd', 2010, 'u', now()) RETURNING id", Long.class);
        jdbc.update("INSERT INTO episodes (series_id, season_number, episode_number, title, duration, video_url, created_at)"
                + " VALUES (?, 1, 1, 't', 40, 'v', now())", seriesId);
        jdbc.update("INSERT INTO series_genres (series_id, genre_id) SELECT ?, id FROM genres WHERE name = 'Drama'", seriesId);
        jdbc.update("INSERT INTO user_favorite_series (user_id, series_id) SELECT id, ? FROM users WHERE username = 'alice'",
                seriesId);

        // El género Drama (de la base heredada) ya no se puede borrar: lo usa la serie
        DataIntegrityViolationException error = assertThrows(DataIntegrityViolationException.class,
                () -> jdbc.update("DELETE FROM genres WHERE name = 'Drama'"));
        assertEquals("23503", PostgresIntegrationTestSupport.sqlState(error));

        // Borrar la serie arrastra todo lo suyo, sin tocar a alice ni el género
        jdbc.update("DELETE FROM series WHERE id = ?", seriesId);
        assertEquals(0, count(jdbc, "episodes"));
        assertEquals(0, count(jdbc, "series_genres"));
        assertEquals(0, count(jdbc, "user_favorite_series"));
        assertEquals(2, count(jdbc, "users"));
        assertEquals(2, count(jdbc, "genres"));
        // Y el CHECK de año de V3 también existe en la base adoptada
        assertEquals("23514", PostgresIntegrationTestSupport.sqlState(assertThrows(DataIntegrityViolationException.class,
                () -> jdbc.update("INSERT INTO series (title, description, release_year, image_url, created_at)"
                        + " VALUES ('Antigua', 'd', 1700, 'u', now())"))));
    }

    /**
     * {@code refresh_tokens} (V4) también es nueva en una base adoptada: se crea
     * completa y su clave foránea hacia el {@code users} HEREDADO sí cascada.
     * Borrar un usuario antiguo borra sus sesiones aunque sus favoritos de
     * películas (FK heredada sin cascada) impidieran borrarlo; aquí se usa
     * {@code root}, que no tiene favoritos.
     */
    @Test
    void laBaseAdoptadaRecibeRefreshTokensConSuCascadaHaciaElUsuarioHeredado() throws Exception {
        String db = createDatabase(true);
        flyway(db).migrate();
        JdbcTemplate jdbc = jdbc(db);

        Map<String, String> rules = new java.util.HashMap<>();
        jdbc.queryForList("SELECT constraint_name, delete_rule FROM information_schema.referential_constraints"
                        + " WHERE constraint_schema = 'public'")
                .forEach(r -> rules.put((String) r.get("constraint_name"), (String) r.get("delete_rule")));
        assertEquals("CASCADE", rules.get("fk_refresh_tokens_user"));
        assertEquals("SET NULL", rules.get("fk_refresh_tokens_replaced_by"));

        jdbc.update("INSERT INTO refresh_tokens (user_id, token_hash, family_id, created_at, expires_at, family_expires_at)"
                + " SELECT id, ?, gen_random_uuid(), now(), now() + interval '1 day', now() + interval '30 days'"
                + " FROM users WHERE username = 'root'", "a".repeat(64));
        assertEquals(1, count(jdbc, "refresh_tokens"));

        jdbc.update("DELETE FROM users WHERE username = 'root'");
        assertEquals(0, count(jdbc, "refresh_tokens"));
        assertEquals(1, count(jdbc, "users"));
    }

    /**
     * Contraste: una base vacía NO recibe fila de baseline (solo V1 a V4) y
     * sí tiene cascadas y CHECK. Garantiza que los dos caminos de arranque
     * producen lo que describe cada test.
     */
    @Test
    void unaBaseVaciaNoRegistraBaselineYRecibeCascadasYCheck() throws Exception {
        String db = createDatabase(false);

        flyway(db).migrate();

        JdbcTemplate jdbc = jdbc(db);
        assertEquals(List.of("1", "2", "3", "4"), jdbc.queryForList(
                "SELECT version FROM flyway_schema_history ORDER BY installed_rank", String.class));
        // Ocho claves foráneas en cascada. V1: géneros->película, favoritos->usuario y
        // favoritos->película. V3: géneros->serie, episodios->serie, favoritos de
        // series->usuario y favoritos de series->serie. V4: refresh tokens->usuario
        // (la del sucesor, fk_refresh_tokens_replaced_by, es SET NULL y no cuenta).
        assertEquals(8, jdbc.queryForObject(
                "SELECT COUNT(*) FROM information_schema.referential_constraints"
                        + " WHERE constraint_schema = 'public' AND delete_rule = 'CASCADE'", Integer.class));
        assertThrows(DataIntegrityViolationException.class, () -> jdbc.update(
                "INSERT INTO movies (title, description, duration, release_year, image_url, video_url, created_at)"
                        + " VALUES ('Antigua', 'd', 100, 1700, 'u', 'v', now())"));
    }

