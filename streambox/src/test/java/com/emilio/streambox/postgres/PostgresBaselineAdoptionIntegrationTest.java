    /**
     * Arranca la aplicación real (Flyway de Spring Boot + Hibernate con
     * {@code ddl-auto=validate}) contra la base heredada y comprueba que:
     * arranca, lee los datos antiguos (con la fecha ya como {@link Instant}) y
     * que borrar una película con favoritos funciona gracias a
     * {@code deleteFromAllFavorites} aunque las claves foráneas heredadas no
     * tengan cascada.
     */
    @Test
    void laAplicacionArrancaSobreUnaBaseAdoptadaYSigueBorrandoPeliculasConFavoritos() throws Exception {
        String db = createDatabase(true);
        PostgresIntegrationTestSupport.postgres(); // asegura el contenedor en marcha

        try (ConfigurableApplicationContext context = new SpringApplication(StreamboxApplication.class).run(
                "--spring.profiles.active=test",
                "--spring.datasource.url=" + url(db),
                "--spring.datasource.username=" + PostgresIntegrationTestSupport.postgres().getUsername(),
                "--spring.datasource.password=" + PostgresIntegrationTestSupport.postgres().getPassword(),
                "--spring.datasource.driver-class-name=org.postgresql.Driver",
                "--server.port=0")) {

            // Si Hibernate no hubiera validado el esquema adoptado, no habría llegado hasta aquí
            MovieRepository movies = context.getBean(MovieRepository.class);
            UserRepository users = context.getBean(UserRepository.class);
            MovieService movieService = context.getBean(MovieService.class);

            User alice = users.findByEmail("alice@test.com").orElseThrow();
            assertNotNull(alice.getCreatedAt());
            assertEquals(2, users.findFavoriteMovies(alice.getId()).size());
            // Las entidades de V3 (Series, Episode) también validan contra la base adoptada
            SeriesRepository series = context.getBean(SeriesRepository.class);
            assertEquals(0, series.count());
            assertEquals(List.of(), series.findFavoritesByUserId(alice.getId()));
            Movie manana = movies.findAllByTitleIgnoreCase("MAÑANA").get(0);
            assertEquals(1999, manana.getReleaseYear());

            movieService.deleteMovie(manana.getId());

            assertEquals(1, users.findFavoriteMovies(alice.getId()).size());
            assertEquals(1, movies.count());
        }
    }

